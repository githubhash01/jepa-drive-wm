#!/usr/bin/env python3
"""
Pose pseudolabels for the KITTI odometry sequences without ground truth (11-21),
generated with stereo ORB-SLAM2 on the color camera pair (image_2 / image_3).

The dataset here is the *color* odometry download, so we run stereo SLAM on
cam2/cam3.  For every sequence this script derives the ORB-SLAM2 settings yaml
directly from the sequence's own ``calib.txt`` (fx/fy/cx/cy from P2, baseline
from P2/P3, image size from the first frame, fps from ``times.txt``) and runs
the headless ``stereo_kitti_color`` runner added to the ORB_SLAM2 checkout
(see paths.ORBSLAM2_ROOT).  Output trajectories are in KITTI pose format
(one 3x4 row-major matrix per line, pose of the left color camera in the
frame of the first camera pose) — the same convention as the ground-truth
``poses/*.txt``, which are the left *gray* camera; the constant ~6 cm
cam0->cam2 offset is negligible for pseudolabels.

Two modes:

  verify    Run on a prefix of a sequence that HAS ground truth and report
            ATE RMSE after rigid (SE3) alignment, the Sim3 scale factor
            (stereo scale sanity) and endpoint drift.  Passes if ATE RMSE
            is below 2%% of the travelled path length.

  generate  Run full sequences (default 11-21), stage the trajectories in
            OUTPUTS_DIR/orbslam_poses/, then install them as
            ``poses/<seq>.txt`` next to the ground truth — but NEVER
            overwriting an existing (ground-truth) pose file.

Run (vjepa2_env, from the repo root):
    PYTHONPATH=src python -m jepa_drive_wm.data.dataset_builders.orbslam_pose_labels verify --seq 0 --frames 700
    PYTHONPATH=src python -m jepa_drive_wm.data.dataset_builders.orbslam_pose_labels generate
    PYTHONPATH=src python -m jepa_drive_wm.data.dataset_builders.orbslam_pose_labels generate --seqs 11,13-15

ORB-SLAM2 runtime prerequisites (already set up on this machine):
    conda env ``orbslam``  — OpenCV 4 C++ libs (conda-forge)
    ~/.local/lib           — Pangolin v0.6
    ORBSLAM2_ROOT built with the ``stereo_kitti_color`` example.
"""

import argparse
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

import cv2
import numpy as np

from jepa_drive_wm.paths import (
    GT_POSES_DIR,
    ORBSLAM2_ROOT,
    OUTPUTS_DIR,
    SEQUENCES_DIR,
)

STAGING_DIR = OUTPUTS_DIR / "orbslam_poses"

# Shared-library dirs the ORB-SLAM2 binary needs at runtime (override if the
# OpenCV conda env or the Pangolin prefix lives elsewhere).
ORBSLAM_LIB_DIRS = os.environ.get(
    "JEPA_ORBSLAM_LIB_DIRS",
    os.pathsep.join(
        [
            str(Path("~/miniconda3/envs/orbslam/lib").expanduser()),
            str(Path("~/.local/lib").expanduser()),
        ]
    ),
)

SETTINGS_TEMPLATE = """\
%YAML:1.0

# Auto-generated by jepa_drive_wm.data.dataset_builders.orbslam_pose_labels for KITTI seq {seq:02d}
# (color stereo pair image_2/image_3, calibration from the sequence calib.txt).

Camera.fx: {fx:.6f}
Camera.fy: {fy:.6f}
Camera.cx: {cx:.6f}
Camera.cy: {cy:.6f}

Camera.k1: 0.0
Camera.k2: 0.0
Camera.p1: 0.0
Camera.p2: 0.0

Camera.width: {width}
Camera.height: {height}

Camera.fps: {fps:.1f}

# stereo baseline times fx
Camera.bf: {bf:.6f}

# Color order of the images (0: BGR, 1: RGB). cv::imread loads BGR.
Camera.RGB: 0

# Close/Far threshold, in baselines (stock KITTI04-12 value).
ThDepth: 40

ORBextractor.nFeatures: 2000
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 12
ORBextractor.minThFAST: 7

# Viewer params are unused headless but MapDrawer still reads them.
Viewer.KeyFrameSize: 0.6
Viewer.KeyFrameLineWidth: 2
Viewer.GraphLineWidth: 1
Viewer.PointSize: 2
Viewer.CameraSize: 0.7
Viewer.CameraLineWidth: 3
Viewer.ViewpointX: 0
Viewer.ViewpointY: -100
Viewer.ViewpointZ: -0.1
Viewer.ViewpointF: 2000
"""


def parse_sequences(spec: str) -> list[int]:
    out: list[int] = []
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            out.extend(range(int(a), int(b) + 1))
        else:
            out.append(int(part))
    seen, seqs = set(), []
    for s in out:
        if not 0 <= s <= 21:
            raise ValueError(f"KITTI odometry sequence out of range 00-21: {s}")
        if s not in seen:
            seen.add(s)
            seqs.append(s)
    return seqs


# --------------------------------------------------------------------------
# Settings generation
# --------------------------------------------------------------------------

def read_projections(seq_dir: Path) -> dict[str, np.ndarray]:
    mats = {}
    for line in (seq_dir / "calib.txt").read_text().splitlines():
        if ":" not in line:
            continue
        key, vals = line.split(":", 1)
        mats[key.strip()] = np.array([float(v) for v in vals.split()]).reshape(3, 4)
    return mats


def write_settings(seq: int, out_path: Path) -> None:
    seq_dir = SEQUENCES_DIR / f"{seq:02d}"
    P2, P3 = (read_projections(seq_dir)[k] for k in ("P2", "P3"))

    # For rectified KITTI, P[0,3] = -fx * baseline_from_cam0, so the cam2/cam3
    # baseline*fx is simply P2[0,3] - P3[0,3]  (~380 => ~0.54 m baseline).
    bf = P2[0, 3] - P3[0, 3]
    if not 300.0 < bf < 500.0:
        raise RuntimeError(f"seq {seq:02d}: implausible Camera.bf={bf:.2f} from calib.txt")

    first = sorted((seq_dir / "image_2").glob("*.png"))[0]
    img = cv2.imread(str(first))
    if img is None:
        raise RuntimeError(f"seq {seq:02d}: cannot read {first}")
    height, width = img.shape[:2]

    times = np.loadtxt(seq_dir / "times.txt")
    fps = (len(times) - 1) / (times[-1] - times[0])

    out_path.write_text(
        SETTINGS_TEMPLATE.format(
            seq=seq,
            fx=P2[0, 0],
            fy=P2[1, 1],
            cx=P2[0, 2],
            cy=P2[1, 2],
            width=width,
            height=height,
            fps=fps,
            bf=bf,
        )
    )


# --------------------------------------------------------------------------
# Running ORB-SLAM2
# --------------------------------------------------------------------------

def n_frames(seq: int) -> int:
    return len((SEQUENCES_DIR / f"{seq:02d}" / "times.txt").read_text().splitlines())


def run_orbslam(
    seq: int, traj_path: Path, max_frames: int = 0, pace: float = 1.0
) -> None:
    """Run stereo_kitti_color on a sequence, writing the trajectory to traj_path."""
    binary = ORBSLAM2_ROOT / "Examples" / "Stereo" / "stereo_kitti_color"
    vocab = ORBSLAM2_ROOT / "Vocabulary" / "ORBvoc.txt"
    if not binary.exists():
        raise RuntimeError(f"{binary} not found — build ORB_SLAM2 first")

    settings = STAGING_DIR / "settings" / f"KITTI{seq:02d}_color.yaml"
    settings.parent.mkdir(parents=True, exist_ok=True)
    write_settings(seq, settings)

    env = dict(os.environ)
    env["LD_LIBRARY_PATH"] = os.pathsep.join(
        filter(None, [ORBSLAM_LIB_DIRS, env.get("LD_LIBRARY_PATH", "")])
    )

    cmd = [
        str(binary),
        str(vocab),
        str(settings),
        str(SEQUENCES_DIR / f"{seq:02d}"),
        str(traj_path),
        str(max_frames),
        str(pace),
    ]
    traj_path.parent.mkdir(parents=True, exist_ok=True)
    log_path = STAGING_DIR / "logs" / f"{seq:02d}.log"
    log_path.parent.mkdir(parents=True, exist_ok=True)

    expected = max_frames if max_frames > 0 else n_frames(seq)
    print(f"[seq {seq:02d}] running ORB-SLAM2 on {expected} frames "
          f"(pace {pace}x, log: {log_path}) ...", flush=True)
    t0 = time.time()
    with open(log_path, "w") as log:
        subprocess.run(cmd, env=env, stdout=log, stderr=subprocess.STDOUT, check=True)
    print(f"[seq {seq:02d}] done in {time.time() - t0:.0f}s", flush=True)

    got = len(traj_path.read_text().splitlines())
    if got != expected:
        raise RuntimeError(
            f"seq {seq:02d}: trajectory has {got} poses but {expected} frames were "
            f"processed — tracking was lost/reset, output would be misaligned. "
            f"See {log_path}."
        )


# --------------------------------------------------------------------------
# Evaluation against ground truth
# --------------------------------------------------------------------------

def load_kitti_poses(path: Path, limit: int = 0) -> np.ndarray:
    """(N, 4, 4) camera-to-world poses from a KITTI-format pose file."""
    rows = np.loadtxt(path)
    if limit > 0:
        rows = rows[:limit]
    poses = np.tile(np.eye(4), (len(rows), 1, 1))
    poses[:, :3, :] = rows.reshape(-1, 3, 4)
    return poses


def align_rigid(est: np.ndarray, gt: np.ndarray, with_scale: bool = False):
    """Umeyama alignment est->gt on (N,3) positions. Returns (s, R, t)."""
    mu_e, mu_g = est.mean(0), gt.mean(0)
    e, g = est - mu_e, gt - mu_g
    C = g.T @ e / len(est)
    U, D, Vt = np.linalg.svd(C)
    S = np.eye(3)
    if np.linalg.det(U) * np.linalg.det(Vt) < 0:
        S[2, 2] = -1
    R = U @ S @ Vt
    s = float(np.trace(np.diag(D) @ S) / e.var(0).sum()) if with_scale else 1.0
    t = mu_g - s * R @ mu_e
    return s, R, t


def evaluate(est_poses: np.ndarray, gt_poses: np.ndarray) -> dict:
    est_p, gt_p = est_poses[:, :3, 3], gt_poses[:, :3, 3]
    length = float(np.linalg.norm(np.diff(gt_p, axis=0), axis=1).sum())

    _, R, t = align_rigid(est_p, gt_p, with_scale=False)
    resid = (est_p @ R.T + t) - gt_p
    ate = float(np.sqrt((resid ** 2).sum(1).mean()))

    s, Rs, ts = align_rigid(est_p, gt_p, with_scale=True)

    return {
        "n": len(est_p),
        "length_m": length,
        "ate_rmse_m": ate,
        "ate_max_m": float(np.linalg.norm(resid, axis=1).max()),
        "ate_pct": 100.0 * ate / length,
        "sim3_scale": s,
        "endpoint_err_m": float(np.linalg.norm(resid[-1])),
    }


# --------------------------------------------------------------------------
# Modes
# --------------------------------------------------------------------------

def cmd_verify(args: argparse.Namespace) -> int:
    seq = args.seq
    gt_file = GT_POSES_DIR / f"{seq:02d}.txt"
    if not gt_file.exists():
        print(f"seq {seq:02d} has no ground truth ({gt_file}); pick one of 00-10")
        return 1

    traj = STAGING_DIR / "verify" / f"{seq:02d}_first{args.frames}.txt"
    run_orbslam(seq, traj, max_frames=args.frames, pace=args.pace)

    est = load_kitti_poses(traj)
    gt = load_kitti_poses(gt_file, limit=len(est))
    m = evaluate(est, gt)

    print(f"\n=== verification: seq {seq:02d}, first {m['n']} frames ===")
    print(f"path length          {m['length_m']:9.1f} m")
    print(f"ATE RMSE (SE3)       {m['ate_rmse_m']:9.2f} m   ({m['ate_pct']:.2f}% of path)")
    print(f"ATE max              {m['ate_max_m']:9.2f} m")
    print(f"endpoint error       {m['endpoint_err_m']:9.2f} m")
    print(f"Sim3 scale           {m['sim3_scale']:9.4f}   (1.0 = metric scale correct)")

    ok = m["ate_pct"] < 2.0 and abs(1.0 - m["sim3_scale"]) < 0.05
    print("\nPASS — trajectory is usable as pose pseudolabels" if ok
          else "\nFAIL — inspect the log and settings before generating")
    return 0 if ok else 1


def cmd_generate(args: argparse.Namespace) -> int:
    seqs = parse_sequences(args.seqs)
    failed = []
    for seq in seqs:
        traj = STAGING_DIR / f"{seq:02d}.txt"
        if traj.exists() and not args.overwrite:
            print(f"[seq {seq:02d}] {traj} exists, skipping (use --overwrite to redo)")
        else:
            try:
                run_orbslam(seq, traj, pace=args.pace)
            except (RuntimeError, subprocess.CalledProcessError) as e:
                print(f"[seq {seq:02d}] FAILED: {e}", file=sys.stderr)
                failed.append(seq)
                continue

        if args.install:
            dst = GT_POSES_DIR / f"{seq:02d}.txt"
            if dst.exists():
                print(f"[seq {seq:02d}] {dst} already exists (ground truth?) — NOT overwriting")
            else:
                shutil.copy2(traj, dst)
                print(f"[seq {seq:02d}] installed -> {dst}")

    if failed:
        print(f"\nfailed sequences: {failed}", file=sys.stderr)
        return 1
    print("\nall sequences done")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="mode", required=True)

    v = sub.add_parser("verify", help="run on a GT sequence prefix and report ATE")
    v.add_argument("--seq", type=int, default=0, help="sequence with GT (default 00)")
    v.add_argument("--frames", type=int, default=700, help="number of frames (default 700)")
    v.add_argument("--pace", type=float, default=1.0,
                   help="playback speed factor; 0 = as fast as possible (default 1.0)")

    g = sub.add_parser("generate", help="generate pseudolabels and install them")
    g.add_argument("--seqs", default="11-21", help="sequences to run (default 11-21)")
    g.add_argument("--pace", type=float, default=1.0)
    g.add_argument("--overwrite", action="store_true", help="re-run even if staged output exists")
    g.add_argument("--no-install", dest="install", action="store_false",
                   help="do not copy results into the poses/ directory")

    args = ap.parse_args()
    return cmd_verify(args) if args.mode == "verify" else cmd_generate(args)


if __name__ == "__main__":
    sys.exit(main())
